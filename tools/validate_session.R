source("tools/docker/latest_versions.R")
onnx_internal_assert_fedora_container(check_latest = FALSE)
# A fresh process verifies inference and namespace lifetime without the optional engine.
library(tidyonnx)
arguments <- commandArgs(trailingOnly = TRUE)
stopifnot(length(arguments) == 1L, !"xgboost" %in% loadedNamespaces())
model <- onnx_load(arguments[1L])
input <- matrix(0, 3, length(model@feature_names))
expected <- onnx_predict(model, input, "raw")
restored <- unserialize(serialize(model, NULL))
stopifnot(!tidyonnx:::onnx_internal_session_alive(restored@session_ptr))
stopifnot(identical(onnx_predict(restored, input, "raw"), expected))
detach("package:tidyonnx", unload = TRUE)
library(tidyonnx)
stopifnot(identical(onnx_predict(model, input, "raw"), expected))
rm(model, restored)
gc()
stopifnot(!"xgboost" %in% loadedNamespaces())
stopifnot(typeof(body(tidyonnx::onnx_run)) == "language")
print(compiler::disassemble(tidyonnx::onnx_run)[[1L]])
cat("Fresh-process inference, RDS, bytecode and namespace reload passed.\n")
