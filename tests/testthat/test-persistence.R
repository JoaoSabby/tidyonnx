test_that("ONNX and RDS round trips restore native sessions", {
  model <- fixture_model()
  x <- matrix(c(0, 2, NA), ncol = 1)
  expected <- onnx_predict(model, x)
  file <- tempfile(fileext = ".onnx")
  rds <- tempfile(fileext = ".rds")
  on.exit(unlink(c(file, rds)), add = TRUE)
  expect_identical(onnx_save(model, file), normalizePath(file, winslash = "/", mustWork = FALSE))
  expect_equal(onnx_predict(file, x), expected)
  loaded <- onnx_load(file)
  expect_true(S7_inherits(loaded, onnx_model))
  expect_equal(loaded@feature_names, "temperature")
  saveRDS(loaded, rds)
  restored <- readRDS(rds)
  expect_false(cpp_session_alive(restored@session_ptr))
  unlink(file)
  expect_equal(onnx_predict(restored, x), expected)
  expect_true(cpp_session_alive(restored@metadata$session_cache$ptr))
  first_pointer <- restored@metadata$session_cache$ptr
  expect_equal(onnx_predict(restored, x), expected)
  expect_identical(restored@metadata$session_cache$ptr, first_pointer)
})

test_that("file-backed persistence reports unavailable backing files", {
  file <- tempfile(fileext = ".onnx")
  rds <- tempfile(fileext = ".rds")
  on.exit(unlink(c(file, rds)), add = TRUE)
  onnx_save(fixture_model(), file)
  model <- onnx_load(file, list(embed_raw_bytes = FALSE))
  expect_length(model@raw_bytes, 0L)
  saveRDS(model, rds)
  expect_equal(onnx_predict(readRDS(rds), matrix(0, 1, 1)),
    onnx_predict(model, matrix(0, 1, 1)))
  unlink(file)
  expect_error(onnx_predict(readRDS(rds), matrix(0, 1, 1)), "Model file")
})

test_that("failed conversion leaves an existing destination unchanged", {
  file <- tempfile(fileext = ".onnx")
  on.exit(unlink(file), add = TRUE)
  writeBin(as.raw(1:10), file)
  expect_error(onnx_save(list(), file), "No serializer")
  expect_identical(readBin(file, "raw", 10), as.raw(1:10))
  onnx_save(fixture_model(), file)
  expect_equal(onnx_load(file)@task_type, "classification_binary")
})

test_that("inspection exposes actual metadata and capabilities", {
  info <- onnx_inspect(fixture_model())
  expect_named(info, c("model", "inputs", "outputs", "features", "engine"))
  expect_true(all(vapply(info, inherits, logical(1), "tbl_df")))
  expect_equal(info$model$producer, "tidyonnx")
  expect_equal(info$model$ml_opset, 3L)
  expect_equal(info$model$trees, 2)
  expect_equal(info$features$name, "temperature")
  expect_equal(info$engine$execution_provider, "cpu")
  expect_output(print(fixture_model()), "native C")
})
